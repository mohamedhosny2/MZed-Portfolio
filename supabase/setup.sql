-- Run once in Supabase SQL Editor for the MZed portfolio project.
-- This script is safe to re-run: policies and storage rules are recreated.

create table if not exists public.projects (
  id bigint generated by default as identity primary key,
  "Title" text not null,
  "Description" text not null default '',
  "Img" text,
  "Link" text,
  "Github" text,
  "Features" jsonb not null default '[]'::jsonb,
  "TechStack" jsonb not null default '[]'::jsonb,
  is_published boolean not null default true,
  order_index integer not null default 0,
  created_at timestamptz not null default now()
);

alter table public.projects add column if not exists is_published boolean not null default true;
alter table public.projects add column if not exists order_index integer not null default 0;

create table if not exists public.certificates (
  id bigint generated by default as identity primary key,
  "Title" text not null default 'Certificate',
  "Img" text not null,
  created_at timestamptz not null default now()
);

alter table public.certificates add column if not exists "Title" text not null default 'Certificate';

create table if not exists public.portfolio_comments (
  id uuid primary key default gen_random_uuid(),
  content text not null,
  user_name text not null,
  profile_image text,
  is_pinned boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text unique not null,
  role text not null check (role in ('admin', 'user')),
  created_at timestamptz not null default now()
);

create table if not exists public.site_settings (
  id text primary key default 'portfolio' check (id = 'portfolio'),
  settings jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

create index if not exists projects_public_order_idx
  on public.projects (is_published, order_index, created_at desc);
create index if not exists comments_created_at_idx
  on public.portfolio_comments (created_at desc);

create or replace function public.is_portfolio_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles
    where id = (select auth.uid()) and role = 'admin'
  );
$$;

grant execute on function public.is_portfolio_admin() to authenticated;

alter table public.projects enable row level security;
alter table public.certificates enable row level security;
alter table public.portfolio_comments enable row level security;
alter table public.profiles enable row level security;
alter table public.site_settings enable row level security;

grant select on public.projects, public.certificates, public.portfolio_comments, public.site_settings to anon, authenticated;
grant insert on public.portfolio_comments to anon, authenticated;
grant all on public.projects, public.certificates, public.portfolio_comments, public.site_settings to authenticated;
grant select on public.profiles to authenticated;
grant usage, select on all sequences in schema public to authenticated;

drop policy if exists "public read published projects" on public.projects;
create policy "public read published projects" on public.projects
  for select to anon, authenticated using (is_published = true);
drop policy if exists "admin manage projects" on public.projects;
create policy "admin manage projects" on public.projects
  for all to authenticated using (public.is_portfolio_admin())
  with check (public.is_portfolio_admin());

drop policy if exists "public read certificates" on public.certificates;
create policy "public read certificates" on public.certificates
  for select to anon, authenticated using (true);
drop policy if exists "admin manage certificates" on public.certificates;
create policy "admin manage certificates" on public.certificates
  for all to authenticated using (public.is_portfolio_admin())
  with check (public.is_portfolio_admin());

drop policy if exists "public read comments" on public.portfolio_comments;
create policy "public read comments" on public.portfolio_comments
  for select to anon, authenticated using (true);
drop policy if exists "public insert comments" on public.portfolio_comments;
create policy "public insert comments" on public.portfolio_comments
  for insert to anon, authenticated
  with check (
    is_pinned = false
    and length(trim(user_name)) between 1 and 60
    and length(trim(content)) between 1 and 200
  );
drop policy if exists "admin manage comments" on public.portfolio_comments;
create policy "admin manage comments" on public.portfolio_comments
  for all to authenticated using (public.is_portfolio_admin())
  with check (public.is_portfolio_admin());

drop policy if exists "users read own profile" on public.profiles;
create policy "users read own profile" on public.profiles
  for select to authenticated using ((select auth.uid()) = id);

drop policy if exists "public read site settings" on public.site_settings;
create policy "public read site settings" on public.site_settings
  for select to anon, authenticated using (true);
drop policy if exists "admin manage site settings" on public.site_settings;
create policy "admin manage site settings" on public.site_settings
  for all to authenticated using (public.is_portfolio_admin())
  with check (public.is_portfolio_admin());

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values
  ('project-images', 'project-images', true, 10485760, array['image/jpeg','image/png','image/webp','image/gif']),
  ('certificate-images', 'certificate-images', true, 10485760, array['image/jpeg','image/png','image/webp','image/gif']),
  ('profile-images', 'profile-images', true, 5242880, array['image/jpeg','image/png','image/webp'])
on conflict (id) do update set
  public = excluded.public,
  file_size_limit = excluded.file_size_limit,
  allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists "public read portfolio images" on storage.objects;
create policy "public read portfolio images" on storage.objects
  for select to anon, authenticated
  using (bucket_id in ('project-images', 'certificate-images', 'profile-images'));

drop policy if exists "admin upload project images" on storage.objects;
create policy "admin upload project images" on storage.objects
  for insert to authenticated
  with check (bucket_id = 'project-images' and public.is_portfolio_admin());
drop policy if exists "admin upload certificate images" on storage.objects;
create policy "admin upload certificate images" on storage.objects
  for insert to authenticated
  with check (bucket_id = 'certificate-images' and public.is_portfolio_admin());
drop policy if exists "public upload profile images" on storage.objects;
create policy "public upload profile images" on storage.objects
  for insert to anon, authenticated
  with check (bucket_id = 'profile-images');

do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'portfolio_comments'
  ) then
    alter publication supabase_realtime add table public.portfolio_comments;
  end if;
end;
$$;
